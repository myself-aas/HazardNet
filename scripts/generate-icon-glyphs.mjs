#!/usr/bin/env node
/**
 * Generate packages/design-system/src/icons.ts - the one icon vocabulary.
 *
 * The decision this implements (audit P1-8 / backlog 10): the app has exactly one icon family.
 * `lucide-react` is the only icon dependency already declared, and it ships plain SVG path data,
 * so the same glyphs can be drawn by `react-native-svg` on the native shell with no new
 * dependency and no second visual weight. What both platforms need is a name -> path map, which
 * is what this script emits:
 *
 *   data/design/icon-registry.json   the decision: family, stroke, sizes, and the names
 *   node_modules/lucide-react        the glyph bodies, at the installed version
 *   packages/design-system/src/icons.ts   the generated single source for web and native
 *
 * `--check` verifies the committed file matches what the registry and the installed package
 * produce, so a dependency bump or a hand-edit fails the gate instead of quietly diverging
 * (__tests__/iconFamily.test.js runs the same check).
 *
 * Note the name: `scripts/generate-icons.mjs` is the older PWA/maskable-icon generator and is
 * unrelated. This script writes glyph data, not images.
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const REGISTRY = join(ROOT, 'data/design/icon-registry.json');
const OUT = join(ROOT, 'packages/design-system/src/icons.ts');
const ICONS_DIR = join(ROOT, 'node_modules/lucide-react/dist/esm/icons');

const kebab = (name) =>
  name
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Za-z])(\d)/g, '$1-$2')
    .toLowerCase();

/** A shim like `alert-circle.mjs` only re-exports its canonical file; follow it one hop. */
function readIconSource(name) {
  let file = join(ICONS_DIR, `${kebab(name)}.mjs`);
  if (!existsSync(file)) throw new Error(`lucide-react has no icon named ${name} (${kebab(name)})`);
  let text = readFileSync(file, 'utf8');
  const shim = text.match(/export \{ default \} from '\.\/([\w.-]+)'/);
  if (shim) {
    file = join(ICONS_DIR, shim[1]);
    text = readFileSync(file, 'utf8');
  }
  return text;
}

/** The `node: [ ... ]` literal, JSON-quoted so it can be parsed without evaluating it. */
function readIconNode(name) {
  const text = readIconSource(name);
  const at = text.indexOf('node: [');
  if (at === -1) throw new Error(`no node data in the lucide source for ${name}`);
  const start = text.indexOf('[', at);
  let depth = 0;
  let end = -1;
  for (let i = start; i < text.length; i += 1) {
    if (text[i] === '[') depth += 1;
    else if (text[i] === ']') {
      depth -= 1;
      if (depth === 0) {
        end = i + 1;
        break;
      }
    }
  }
  if (end === -1) throw new Error(`unbalanced node literal for ${name}`);
  const literal = text.slice(start, end).replace(/([{,]\s*)([A-Za-z_][\w-]*)\s*:/g, '$1"$2":');
  const node = JSON.parse(literal);
  // `key` is React's reconciliation hint; it carries nothing to either renderer.
  return node.map(([tag, attrs]) => {
    const { key, ...rest } = attrs;
    void key;
    return [tag, rest];
  });
}

function generate() {
  const registry = JSON.parse(readFileSync(REGISTRY, 'utf8'));
  const { version } = JSON.parse(readFileSync(join(ROOT, 'node_modules/lucide-react/package.json'), 'utf8'));
  const names = [...registry.names].sort();

  const entries = names.map((name) => {
    const node = readIconNode(name);
    const body = node
      .map(([tag, attrs]) => `    [${JSON.stringify(tag)}, ${JSON.stringify(attrs)}]`)
      .join(',\n');
    return `  ${JSON.stringify(name)}: [\n${body},\n  ]`;
  });

  return `/**
 * GENERATED FILE - do not edit.
 *
 * One icon family for both platforms, generated by scripts/generate-icon-glyphs.mjs from
 * data/design/icon-registry.json and lucide-react@${version} (the one icon dependency the repo
 * declares). Web renders these names with \`lucide-react\`; the native shell renders the same path
 * data with \`react-native-svg\`, so an icon means the same thing on both.
 *
 * To add an icon: add its lucide name to the registry and run \`npm run icons:build\`.
 * \`__tests__/iconFamily.test.js\` fails if a call site imports a name that is not here.
 */

/** The decided family. Not a preference: the only icon package declared for this app. */
export const ICON_FAMILY = ${JSON.stringify(registry.family)} as const;

/** The package that owns the glyph bodies on web. Native renders ICON_PATHS instead. */
export const ICON_PACKAGE = ${JSON.stringify(registry.package)} as const;

/** Lucide's own version these paths were generated from. */
export const ICON_SOURCE_VERSION = ${JSON.stringify(version)} as const;

/**
 * One stroke weight for the whole app. Lucide's default is 2, which reads heavy next to
 * Apple's hairlines (skill3 bans the thick-stroke look); at 1.75 the glyphs match the
 * 1px border weight and stay legible at 14-16px.
 */
export const ICON_STROKE = ${registry.strokeWidth} as const;

/** Named sizes. The values are the same on web (px) and native (dp/pt). */
export const ICON_SIZES = ${JSON.stringify(registry.sizes, null, 2)} as const;

/** Every icon name the app is allowed to use. */
export const ICON_NAMES = [
${names.map((n) => `  ${JSON.stringify(n)},`).join('\n')}
] as const;

export type IconName = (typeof ICON_NAMES)[number];

/** \`[tag, attributes]\`, the subset of SVG the family uses. */
export type IconNode = readonly (readonly [string, Readonly<Record<string, string | number>>])[];

/**
 * Name -> glyph. Data only: no React, no DOM, so the native shell can consume it as-is.
 * The 24px grid and \`viewBox="0 0 24 24"\` are the family's contract on both platforms.
 */
export const ICON_PATHS: Readonly<Record<IconName, IconNode>> = {
${entries.join(',\n')},
};

/** The family's own coordinate system. Both renderers must set exactly this viewBox. */
export const ICON_VIEW_BOX = ${JSON.stringify(registry.viewBox)} as const;

export function isIconName(value: string): value is IconName {
  return (ICON_NAMES as readonly string[]).includes(value);
}
`;
}

const output = generate();
if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== output) {
    console.error('icons.ts is out of date with data/design/icon-registry.json - run: npm run icons:build');
    process.exit(1);
  }
  console.log('icons.ts matches the registry and the installed lucide-react');
} else {
  writeFileSync(OUT, output);
  console.log(`wrote packages/design-system/src/icons.ts (${output.split('\n').length} lines)`);
}
